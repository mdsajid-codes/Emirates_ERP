import React, { useState, useEffect } from 'react';
import { useNavigate, useParams, Link } from 'react-router-dom';
import { motion } from 'framer-motion';
import { ArrowLeft, Save, Sparkles, Plus } from 'lucide-react';
import { useAccounting } from '../../context/AccountingContext';
import { coaApi } from '../../api/coaApi';
import { toast } from 'react-toastify';

const DIMENSION_OPTIONS = [
  { type: 'ITEM', label: 'Item / SKU' },
  { type: 'WAREHOUSE', label: 'Warehouse' },
  { type: 'FIXED_ASSET', label: 'Fixed Asset' },
  { type: 'EMPLOYEE', label: 'Employee' },
  { type: 'TAX_TYPE', label: 'Tax Type' },
  { type: 'COMPANY', label: 'Company (Partner)' },
  { type: 'CONTRACT', label: 'Project / Contract' },
  { type: 'CASH_FLOW_ITEM', label: 'Cash Flow Item' },
  { type: 'EXPENSE_ITEM', label: 'Expense Item' },
  { type: 'INCOME_ITEM', label: 'Income Item' },
  { type: 'BANK_ACCOUNT', label: 'Bank Account' },
];

export default function CoaFormPage() {
  const { id } = useParams();
  const navigate = useNavigate();
  const isEdit = !!id;
  
  const { accounts, sections, parentGroups, refresh } = useAccounting();

  const [formData, setFormData] = useState({
    accountCode: '',
    description: '',
    accountType: 'DEBIT',
    section: '',
    parentGroup: '',
    parentId: '',
    currency: 'AED',
    isOffBalance: false,
    isQuantitative: false,
    details: '',
  });

  const [selectedDimensions, setSelectedDimensions] = useState([]);
  const [customParentGroup, setCustomParentGroup] = useState('');
  const [isCustomParent, setIsCustomParent] = useState(false);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (isEdit) {
      fetchAccount();
    }
  }, [id]);

  const fetchAccount = async () => {
    setLoading(true);
    try {
      const res = await coaApi.getById(id);
      const data = res.data?.data;
      if (data) {
        setFormData({
          accountCode: data.accountCode || '',
          description: data.description || '',
          accountType: data.accountType || 'DEBIT',
          section: data.section || '',
          parentGroup: data.parentGroup || '',
          parentId: data.parentId || '',
          currency: data.currency || 'AED',
          isOffBalance: !!data.isOffBalance,
          isQuantitative: !!data.isQuantitative,
          details: data.details || '',
        });
        setSelectedDimensions(
          (data.dimensions || []).map(d => d.dimensionType)
        );
      }
    } catch (err) {
      toast.error('Failed to fetch account details');
      navigate('/account-dashboard/chart-of-accounts');
    } finally {
      setLoading(false);
    }
  };

  const handleInputChange = (e) => {
    const { name, value, type, checked } = e.target;
    setFormData(prev => ({
      ...prev,
      [name]: type === 'checkbox' ? checked : value
    }));
  };

  const toggleDimension = (type) => {
    setSelectedDimensions(prev =>
      prev.includes(type)
        ? prev.filter(t => t !== type)
        : [...prev, type]
    );
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setLoading(true);

    try {
      let resolvedParentId = formData.parentId ? parseInt(formData.parentId) : null;

      // If custom parent is requested, check if it already exists or create it
      if (isCustomParent) {
        if (!customParentGroup || !formData.parentGroup) {
          throw new Error('Please fill in both parent code and parent description.');
        }

        // Check if the parent code already exists in our context accounts list
        const existingParent = accounts.find(acc => acc.accountCode === customParentGroup);
        if (existingParent) {
          resolvedParentId = existingParent.accountId;
          toast.info(`Using existing parent group: ${existingParent.description}`);
        } else {
          const parentPayload = {
            accountCode: customParentGroup,
            description: formData.parentGroup,
            accountType: 'DEBIT_CREDIT',
            section: 'ACCOUNTS_GROUP',
            parentId: null,
            isOffBalance: false,
            isQuantitative: false,
            currency: formData.currency,
            details: 'Autogenerated Parent Group',
            dimensions: []
          };

          const parentRes = await coaApi.create(parentPayload);
          if (parentRes.data?.data?.accountId) {
            resolvedParentId = parentRes.data.data.accountId;
            toast.success(`Parent group ${formData.parentGroup} created!`);
          }
        }
      }

      const payload = {
        ...formData,
        parentId: resolvedParentId,
        dimensions: selectedDimensions.map(d => ({
          dimensionType: d,
          trackAmount: true,
          trackQuantitative: false,
          turnoversOnly: false
        }))
      };

      if (isEdit) {
        await coaApi.update(id, payload);
        toast.success('Account updated successfully!');
      } else {
        await coaApi.create(payload);
        toast.success('Account created successfully!');
      }
      refresh();
      navigate('/account-dashboard/chart-of-accounts');
    } catch (err) {
      toast.error(err.response?.data?.message || err.message || 'Failed to save account');
    } finally {
      setLoading(false);
    }
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.3 }}
      className="flex-1 flex flex-col overflow-hidden p-6 bg-background text-foreground"
    >
      {/* Header */}
      <div className="mb-6">
        <Link
          to="/account-dashboard/chart-of-accounts"
          className="inline-flex items-center gap-2 text-sm text-foreground-muted hover:text-foreground mb-2 transition-colors"
        >
          <ArrowLeft className="h-4 w-4" />
          Back to list
        </Link>
        <h1 className="text-2xl font-bold tracking-tight">
          {isEdit ? 'Edit Account' : 'Create New GL Account'}
        </h1>
      </div>

      {/* Form Card */}
      <div className="flex-1 overflow-y-auto bg-card border border-border rounded-theme p-6 shadow-sm w-full">
        <form onSubmit={handleSubmit} className="space-y-6">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            
            {/* Account Code */}
            <div>
              <label htmlFor="accountCode" className="block text-sm font-semibold mb-2">Account Code *</label>
              <input
                id="accountCode"
                name="accountCode"
                type="text"
                required
                disabled={isEdit || loading}
                value={formData.accountCode}
                onChange={handleInputChange}
                placeholder="e.g. 1001001"
                className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary disabled:opacity-60"
              />
            </div>

            {/* Description */}
            <div>
              <label htmlFor="description" className="block text-sm font-semibold mb-2">Description *</label>
              <input
                id="description"
                name="description"
                type="text"
                required
                disabled={loading}
                value={formData.description}
                onChange={handleInputChange}
                placeholder="e.g. Cash on Hand"
                className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
              />
            </div>

            {/* Account Type */}
            <div>
              <label htmlFor="accountType" className="block text-sm font-semibold mb-2">Account Type *</label>
              <select
                id="accountType"
                name="accountType"
                required
                disabled={loading}
                value={formData.accountType}
                onChange={handleInputChange}
                className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
              >
                <option value="DEBIT">DEBIT</option>
                <option value="CREDIT">CREDIT</option>
                <option value="DEBIT_CREDIT">DEBIT_CREDIT</option>
              </select>
            </div>

            {/* Section */}
            <div>
              <label htmlFor="section" className="block text-sm font-semibold mb-2">Account Section *</label>
              <select
                id="section"
                name="section"
                required
                disabled={loading}
                value={formData.section}
                onChange={handleInputChange}
                className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
              >
                <option value="">-- Select Section --</option>
                {sections.map(sec => (
                  <option key={sec} value={sec}>{sec}</option>
                ))}
              </select>
            </div>

            {/* Parent Account */}
            <div>
              <div className="flex items-center justify-between mb-2">
                <label htmlFor="parentId" className="text-sm font-semibold">Parent Account / Group</label>
                <button
                  type="button"
                  onClick={() => setIsCustomParent(!isCustomParent)}
                  className="text-xs text-primary font-semibold hover:underline flex items-center gap-1"
                >
                  <Plus className="h-3 w-3" />
                  {isCustomParent ? 'Select Existing' : 'Create New Parent Group'}
                </button>
              </div>

              {isCustomParent ? (
                <div className="border border-border/80 p-3 rounded-theme bg-background-muted/20 space-y-3">
                  <div>
                    <label className="block text-[11px] font-bold uppercase tracking-wider text-foreground-muted mb-1">Parent Code *</label>
                    <input
                      type="text"
                      required={isCustomParent}
                      value={customParentGroup} // Using existing customParentGroup string as temporary holder or custom code
                      onChange={(e) => setCustomParentGroup(e.target.value)}
                      placeholder="e.g. 1000000"
                      className="w-full px-3 py-1.5 bg-background border border-border rounded-theme text-sm focus:outline-none focus:border-primary"
                    />
                  </div>
                  <div>
                    <label className="block text-[11px] font-bold uppercase tracking-wider text-foreground-muted mb-1">Parent Description *</label>
                    <input
                      type="text"
                      required={isCustomParent}
                      value={formData.parentGroup} // reusing parentGroup string field for custom description
                      onChange={(e) => setFormData(prev => ({ ...prev, parentGroup: e.target.value }))}
                      placeholder="e.g. Current Assets"
                      className="w-full px-3 py-1.5 bg-background border border-border rounded-theme text-sm focus:outline-none focus:border-primary"
                    />
                  </div>
                </div>
              ) : (
                <select
                  id="parentId"
                  name="parentId"
                  disabled={loading}
                  value={formData.parentId || ''}
                  onChange={handleInputChange}
                  className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
                >
                  <option value="">-- No Parent (Root Node) --</option>
                  {accounts
                    .filter(acc => acc.accountId !== parseInt(id)) // avoid self-parenting
                    .map(acc => (
                      <option key={acc.accountId} value={acc.accountId}>
                        {acc.accountCode} - {acc.description} ({acc.section})
                      </option>
                    ))
                  }
                </select>
              )}
            </div>

            {/* Currency */}
            <div>
              <label htmlFor="currency" className="block text-sm font-semibold mb-2">Currency</label>
              <select
                id="currency"
                name="currency"
                disabled={loading}
                value={formData.currency}
                onChange={handleInputChange}
                className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
              >
                <option value="AED">AED</option>
                <option value="USD">USD</option>
                <option value="EUR">EUR</option>
                <option value="GBP">GBP</option>
              </select>
            </div>
          </div>

          {/* Toggle Switches */}
          <div className="flex gap-8 border-t border-border/60 pt-4">
            <label className="flex items-center gap-3 cursor-pointer">
              <input
                type="checkbox"
                name="isQuantitative"
                checked={formData.isQuantitative}
                onChange={handleInputChange}
                className="w-4.5 h-4.5 text-primary rounded border-border focus:ring-primary focus:ring-offset-2"
              />
              <span className="text-sm font-medium">Is Quantitative (Track Qty)</span>
            </label>

            <label className="flex items-center gap-3 cursor-pointer">
              <input
                type="checkbox"
                name="isOffBalance"
                checked={formData.isOffBalance}
                onChange={handleInputChange}
                className="w-4.5 h-4.5 text-primary rounded border-border focus:ring-primary focus:ring-offset-2"
              />
              <span className="text-sm font-medium">Is Off-Balance</span>
            </label>
          </div>

          {/* Dimensions Multi-chip Picker */}
          <div className="border-t border-border/60 pt-4">
            <h3 className="text-sm font-bold uppercase tracking-wider text-primary mb-3 flex items-center gap-2">
              <Sparkles className="h-4 w-4" />
              Dimension Tracking
            </h3>
            <p className="text-xs text-foreground-muted mb-3">
              Tag transactions to split this account's movements across sub-ledgers.
            </p>
            <div className="flex flex-wrap gap-2">
              {DIMENSION_OPTIONS.map(dim => {
                const active = selectedDimensions.includes(dim.type);
                return (
                  <button
                    key={dim.type}
                    type="button"
                    onClick={() => toggleDimension(dim.type)}
                    className={`px-3 py-1.5 rounded-full text-xs font-semibold border transition-all ${
                      active
                        ? 'bg-primary/15 text-primary border-primary/40'
                        : 'bg-background text-foreground-muted border-border hover:border-foreground-muted'
                    }`}
                  >
                    {dim.label}
                  </button>
                );
              })}
            </div>
          </div>

          {/* Details */}
          <div className="border-t border-border/60 pt-4">
            <label htmlFor="details" className="block text-sm font-semibold mb-2">Details / Notes</label>
            <textarea
              id="details"
              name="details"
              rows="3"
              disabled={loading}
              value={formData.details}
              onChange={handleInputChange}
              placeholder="Additional internal audit notes or context..."
              className="w-full px-3 py-2 bg-background border border-border rounded-theme text-foreground focus:outline-none focus:border-primary"
            />
          </div>

          {/* Submit */}
          <div className="flex justify-end gap-3 border-t border-border/60 pt-4">
            <button
              type="button"
              onClick={() => navigate('/account-dashboard/chart-of-accounts')}
              className="px-4 py-2 border border-border text-foreground hover:bg-background-muted transition-colors rounded-theme text-sm font-semibold"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={loading}
              className="flex items-center gap-2 bg-primary text-primary-foreground hover:opacity-90 px-4 py-2 rounded-theme text-sm font-semibold shadow"
            >
              <Save className="h-4 w-4" />
              {loading ? 'Saving...' : 'Save Account'}
            </button>
          </div>
        </form>
      </div>
    </motion.div>
  );
}
